    // ⚡ Диалог → короткое тире «–» в начало каждой реплики
       function formatDialogue(text) {
        if (!text) return '';
        var dialogCb = document.getElementById('edtDialog');
        var dialogEnabled = dialogCb ? dialogCb.checked : true;
        if (!dialogEnabled) return text;

        var lines = String(text).split('\n')
            .map(function (l) { return l.replace(/[ \t\u00a0]+/g, ' ').trim(); })
            .filter(Boolean);
        if (lines.length < 2) return text;

        var hasQuoteMarkers = lines.some(function (l) { return /^>/.test(l); });
        if (hasQuoteMarkers) return text;

        // ═══════════════════════════════════════════════════════════
        // ⚡ НЕ трогаем нумерованные/маркированные списки
        // ═══════════════════════════════════════════════════════════
        var isNumberedList = lines.some(function (l) {
            return /^\s*\d+[.)]\s/.test(l);       // «1. », «2) »
        });
        if (isNumberedList) {
            // Только нормализуем уже существующие тире, новых НЕ добавляем
            return lines.map(function (l) {
                if (/^[-–—]\s/.test(l)) {
                    return '– ' + l.replace(/^[-–—]+\s*/, '');
                }
                return l;
            }).join('\n');
        }
        // ═══════════════════════════════════════════════════════════

        var dashedCount = lines.filter(function (l) { return /^[-–—]\s/.test(l); }).length;

        // Уже все с тире — приводим к короткому «– »
        if (dashedCount === lines.length) {
            return lines.map(function (l) {
                return '– ' + l.replace(/^[-–—]+\s*/, '');
            }).join('\n');
        }

        // ⚡ Диалог — только если есть МИНИМУМ 2 тире
var lastIsShort   = lines[lines.length - 1].length <= 100;      // было 40
var allShort      = lines.filter(function (l) { return l.length <= 200; }).length === lines.length;  // было 80
var linesTwoShort = lines.length >= 2 && allShort;
var isDialogue    = hasAnyDash
                 || hasQuestion
                 || linesTwoShort
                 || (lines.length >= 3 && lastIsShort);

        if (!isDialogue) {
            // Есть отдельные тире — нормализуем ТОЛЬКО их, остальные строки не трогаем
            return lines.map(function (l) {
                if (/^[-–—]\s/.test(l)) {
                    return '– ' + l.replace(/^[-–—]+\s*/, '');
                }
                return l;
            }).join('\n');
        }

        return lines.map(function (l) {
            return '– ' + l.replace(/^[-–—]+\s*/, '');
        }).join('\n');
    }
