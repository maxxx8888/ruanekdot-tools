            if (/^\d{1,2}:\d{2}\s*$/.test(s)) return '';

            // 10) Упоминание «@user» в конце строки с текстом — оставить текст, убрать упоминание
            s = s.replace(/\s+@[a-zA-Z0-9_.]{2,30}\s*$/g, '');

