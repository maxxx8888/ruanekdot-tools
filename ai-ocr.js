    function capitalizeFirst(t) { return t ? t.charAt(0).toUpperCase() + t.slice(1) : ''; }

    function capitalizeSentences(text) {
        if (!text) return '';
        var r = text;
        r = r.replace(/([.!?…])\s+([а-яёa-z])/g, function (m, p1, p2) { return p1 + ' ' + p2.toUpperCase(); });
        r = capitalizeFirst(r);
        r = r.replace(/(^|\n\n)([а-яёa-z])/g, function (m, p1, p2) { return p1 + p2.toUpperCase(); });
        r = r.replace(/(^|\n)—\s+([а-яёa-z])/g, function (m, p1, p2) { return p1 + '— ' + p2.toUpperCase(); });
        return r;
    }

    function joinSoftLineBreaks(text) {
        if (!text) return '';
        var lines = String(text).split('\n');
        var out = [];
        function isListLine(s) { return /^\s*(>|—|•|\*|–|-|\d+[.)])\s/.test(s); }
        for (var i = 0; i < lines.length; i++) {
            var line = lines[i];
            var prev = out.length > 0 ? out[out.length - 1] : null;
            var prevIsList = prev !== null && isListLine(prev);
            var lineIsList = isListLine(line);
            if (prev !== null && prev !== '' && line !== '' &&
                /^[а-яёa-z]/.test(line) &&
                !/[.!?…:;]\s*$/.test(prev) &&
                !prevIsList && !lineIsList &&
                !/^\s*[•·\-–—*]\s/.test(line) &&
                !/^\s*\d+[.)]\s/.test(line) && !/^\s*\d+[.)]\s/.test(prev)) {
                out[out.length - 1] = prev + ' ' + line;
            } else {
                out.push(line);
            }
        }
        return out.join('\n');
    }

