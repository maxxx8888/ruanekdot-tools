    function extractImageUrl(html, uriList, plainText) {
        if (html) {
            var m = html.match(/<img[^>]+src=["']([^"']+)["']/i);
            if (m && m[1] && m[1].indexOf('data:image') !== 0) return m[1];
            m = html.match(/https?:\/\/[^\s"'<>]+\.(?:jpg|jpeg|png|gif|webp|bmp)(?:\?[^\s"'<>]*)?/i);
            if (m) return m[0];
        }
        if (uriList) {
            var lines = uriList.split(/\r?\n/).map(function (l) { return l.trim(); }).filter(Boolean);
            for (var i = 0; i < lines.length; i++) {
                if (/^https?:\/\/.+\.(jpe?g|png|gif|webp|bmp)(\?|$)/i.test(lines[i])) return lines[i];
            }
        }
        if (plainText) {
            var m2 = plainText.match(/https?:\/\/[^\s"'<>]+\.(?:jpg|jpeg|png|gif|webp|bmp)(?:\?[^\s"'<>]*)?/i);
            if (m2) return m2[0];
        }
        return null;
    }
