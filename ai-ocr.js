    function getTextViaAI(blob, proxyUrl) {
        return new Promise(function (resolve, reject) {
            var reader = new FileReader();
            reader.onloadend = function () {
                var base64 = String(reader.result || '');
                var base64Data = base64.split(',')[1];
                var ctrl = new AbortController();
                var t = setTimeout(function () { ctrl.abort(); }, 55000);
                fetch(proxyUrl, {
                    method: 'POST',
                    headers: { 'Content-Type': 'application/json' },
                    body: JSON.stringify({ action: 'ocrOnly', imageBase64: base64Data }),
                    signal: ctrl.signal
                }).then(function (r) {
                    clearTimeout(t);
                    if (!r.ok) {
                        return r.text().then(function (txt) {
                            throw new Error('AI-OCR ' + r.status + ': ' + txt.substring(0, 200));
                        });
                    }
                    return r.json();
                }).then(function (data) {
                    if (data && data.success && data.text && data.text.length >= 5) {
                        resolve({
                            text: data.text,
                            title: data.title || '',
                            tags: data.tags || '',
                            comment: data.comment || '',
                            source: data.source || 'cloudflare'
                        });
                    } else {
                        reject(new Error('AI-OCR вернул пусто'));
                    }
                }).catch(function (e) {
                    clearTimeout(t);
                    reject(e);
                });
            };
            reader.onerror = function () { reject(new Error('Ошибка чтения blob')); };
            reader.readAsDataURL(blob);
        });
    }

