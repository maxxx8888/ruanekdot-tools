    function stepDownResize(img, targetWidth, targetHeight) {
        var currentCanvas = document.createElement('canvas');
        var currentCtx = currentCanvas.getContext('2d');
        currentCanvas.width = img.width; currentCanvas.height = img.height;
        currentCtx.drawImage(img, 0, 0);
        while (currentCanvas.width / 2 >= targetWidth && currentCanvas.height / 2 >= targetHeight) {
            var tc = document.createElement('canvas');
            var tctx = tc.getContext('2d');
            tc.width = Math.floor(currentCanvas.width / 2);
            tc.height = Math.floor(currentCanvas.height / 2);
            tctx.imageSmoothingEnabled = true;
            tctx.imageSmoothingQuality = 'high';
            tctx.drawImage(currentCanvas, 0, 0, currentCanvas.width, currentCanvas.height, 0, 0, tc.width, tc.height);
            currentCanvas = tc;
        }
        var fc = document.createElement('canvas');
        fc.width = targetWidth; fc.height = targetHeight;
        var fctx = fc.getContext('2d');
        fctx.imageSmoothingEnabled = true;
        fctx.imageSmoothingQuality = 'high';
        fctx.drawImage(currentCanvas, 0, 0, currentCanvas.width, currentCanvas.height, 0, 0, targetWidth, targetHeight);
        return fc;
    }
    function applySharpen(canvas, strength) {
        strength = strength || 0.4;
        var ctx = canvas.getContext('2d');
        var w = canvas.width, h = canvas.height;
        var imageData = ctx.getImageData(0, 0, w, h);
        var data = imageData.data;
        var copy = new Uint8ClampedArray(data);
        for (var y = 1; y < h - 1; y++) {
            for (var x = 1; x < w - 1; x++) {
                var i = (y * w + x) * 4;
                for (var c = 0; c < 3; c++) {
                    var sum = 0;
                    sum += copy[((y-1)*w + x-1)*4 + c]; sum += copy[((y-1)*w + x  )*4 + c]; sum += copy[((y-1)*w + x+1)*4 + c];
                    sum += copy[( y   *w + x-1)*4 + c]; sum += copy[( y   *w + x+1)*4 + c];
                    sum += copy[((y+1)*w + x-1)*4 + c]; sum += copy[((y+1)*w + x  )*4 + c]; sum += copy[((y+1)*w + x+1)*4 + c];
                    var blurred = sum / 8;
                    var center = copy[i + c];
                    data[i + c] = Math.max(0, Math.min(255, center + strength * (center - blurred)));
                }
            }
        }
        ctx.putImageData(imageData, 0, 0);
    }
