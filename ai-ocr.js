    function findCensorRange(text) {
        if (!text) return { start: 0, end: 1 };
        var L = String(text).length;
        if (L < 2) return { start: 0, end: 1 };
        var lower = String(text).toLowerCase();
        var rootPos = -1, rootLen = 0;
        for (var i = 0; i < PROFANITY_ROOTS.length; i++) {
            var root = PROFANITY_ROOTS[i];
            var pos = lower.indexOf(root);
            if (pos === -1) continue;
            if (rootPos === -1 || pos < rootPos || (pos === rootPos && root.length > rootLen)) {
                rootPos = pos; rootLen = root.length;
            }
        }
        var maskStart, maskLen;
        if (rootPos === -1) { maskStart = Math.max(1, Math.floor(L / 2) - 1); maskLen = 1; }
        else if (rootLen <= 2 && rootPos === 0) { maskStart = 1; maskLen = 1; }
        else if (rootLen <= 2) { maskStart = Math.max(0, rootPos - 1); maskLen = 2; }
        else {
            maskStart = rootPos + Math.ceil(rootLen / 2);
            maskLen = 1;
            if (maskStart > L - 2) maskStart = Math.max(rootPos + 1, L - 2);
        }
        if (maskStart < 1) maskStart = 1;
        var maskEnd = Math.min(maskStart + maskLen, L - 1);
        if (maskEnd <= maskStart) maskEnd = Math.min(maskStart + 1, L);
        return { start: maskStart, end: maskEnd };
    }

