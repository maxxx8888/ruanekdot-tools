    function smartGenerateTitle(text) {
        if (!text) return 'Без названия';
        function isJunkLine(line) {
            var s = String(line || '').trim();
            if (!s) return true;
            if (s.length < 8) return true;
            if (/^[>•\-\*]\s*/.test(s)) return true;
            if (/^\d/.test(s)) return true;
            if (/^[={\[\]|\\\/<>]/.test(s)) return true;
            if (/^[A-ZА-Я]\s+\S/.test(s)) return true;
            if (/^@/.test(s)) return true;
            if (/^(подписаться|follow|subscrib|исходный\s+язык|переведен|translated)/i.test(s)) return true;
            if (/смотреть\s+действи|популярные|показать\s+все/i.test(s)) return true;
            if (/\d+[,.]?\d*\s*(тыс|млн|k|m)\.?/i.test(s)) return true;
            if (/\d{1,2}\s*ч\./.test(s)) return true;
            var letters = (s.match(/[А-Яа-яЁёA-Za-z]/g) || []).length;
            var punct = (s.match(/[^\wа-яёА-ЯЁ\s]/g) || []).length;
            var total = s.replace(/\s/g, '').length;
            if (total > 0 && (punct / total) > 0.4 && letters < 8) return true;
            if (letters < 8) return true;
            return false;
        }
        var lines = String(text).split('\n')
            .map(function (l) { return l.replace(/^[—\-–>\s•\*]+/, '').trim(); })
            .filter(function (l) { return !isJunkLine(l); });
        if (!lines.length) {
            var allLines = String(text).split('\n')
                .map(function (l) { return l.replace(/^[—\-–>\s•\*]+/, '').trim(); })
                .filter(function (l) { return l.length > 15; });
            if (!allLines.length) return 'Без названия';
            allLines.sort(function (a, b) { return b.length - a.length; });
            var fallback = allLines[0];
            if (fallback.length > 70) fallback = fallback.substring(0, 67).replace(/\s+\S*$/, '') + '…';
            return capitalizeFirst(fallback);
        }
        var candidates = [];
        for (var i = 0; i < lines.length; i++) {
            var line = lines[i], score = 0;
            var len = line.length;
            if (/\?/.test(line)) score += 8;
            if (/!/.test(line)) score += 3;
            if (len >= 25 && len <= 70) score += 6;
            else if (len > 80) score -= 4;
            else if (len < 20) score -= 3;
            if (i === lines.length - 1) score += 10;
            if (i === 0) score -= 3;
            candidates.push({ line: line, score: score });
        }
        candidates.sort(function (a, b) { return b.score - a.score; });
        var best = candidates[0].line;
        var MAX_TITLE_LEN = 70;
        if (best.length > MAX_TITLE_LEN) {
            var words = best.split(' '), title = '';
            for (var w = 0; w < words.length; w++) {
                var next = title ? title + ' ' + words[w] : words[w];
                if (next.length > MAX_TITLE_LEN - 3) break;
                title = next;
            }
            best = (title || best.substring(0, MAX_TITLE_LEN - 3)).replace(/[,;:]+$/, '');
        }
        best = best.replace(/^["«»'`]+|["«»'`]+$/g, '').replace(/[.!?]+$/, '').trim();
        return capitalizeFirst(best);
    }

