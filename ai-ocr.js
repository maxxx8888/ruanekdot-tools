let _mozjpegInitPromise = null;

async function initMozJpeg() {
    if (_mozjpegInitPromise) return _mozjpegInitPromise;
    _mozjpegInitPromise = (async () => {
        const module = await import('https://esm.sh/@jsquash/jpeg@1.6.0');
        const { init, default: encode } = module;
        const wasmBuf = await fetch('https://esm.sh/@jsquash/jpeg@1.6.0/es2022/mozjpeg_enc.wasm')
            .then(r => r.arrayBuffer());
        const wasmModule = await WebAssembly.compile(wasmBuf);
        await init(wasmModule);
        return { encode };
    })();
    return _mozjpegInitPromise;
}

function compressImage(file) {
    return new Promise(function (resolve, reject) {
        var img = new Image();
        img.onload = async function () {
            try {
                var maxDim = 960, nw, nh;
                if (img.width > maxDim || img.height > maxDim) {
                    var r = maxDim / Math.max(img.width, img.height);
                    nw = Math.round(img.width * r);
                    nh = Math.round(img.height * r);
                } else {
                    nw = img.width;
                    nh = img.height;
                }

                var canvas = stepDownResize(img, nw, nh);
                try { applySharpen(canvas, 0.4); } catch (e) {}

                var ctx = canvas.getContext('2d');
                var imageData = ctx.getImageData(0, 0, nw, nh);

                try {
                    var { encode } = await initMozJpeg();
                    // ⚡ MozJPEG: quality 75 (как iLoveIMG), optimize: true для лучшего сжатия
                    var jpegBuffer = await encode(imageData, { quality: 75, optimize: true });
                    var blob = new Blob([jpegBuffer], { type: 'image/jpeg' });
                    console.log('🗜️ MozJPEG: ' + (file.size / 1024).toFixed(0) + ' KB → ' + (blob.size / 1024).toFixed(0) + ' KB');
                    resolve(blob);
                } catch (err) {
                    console.warn('⚠️ MozJPEG недоступен, fallback на Canvas:', err.message);
                    canvas.toBlob(function (blob) {
                        resolve(blob);
                    }, 'image/jpeg', 0.78);
                }
            } catch (e) {
                reject(e);
            }
        };
        img.onerror = function () { reject(new Error('Ошибка загрузки изображения')); };
        img.src = URL.createObjectURL(file);
    });
}
